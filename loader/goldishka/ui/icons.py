def _gear() -> QPainterPath:
    path = QPainterPath()
    path.addEllipse(QRectF(7.2, 7.2, 9.6, 9.6))
    for i in range(8):
        tooth = QPainterPath()
        tooth.addRoundedRect(QRectF(-1.5, -10.6, 3.0, 4.0), 1.2, 1.2)
        t = QTransform()
        t.translate(12, 12)
        t.rotate(i * 45)
        path.addPath(t.map(tooth))
    path.addEllipse(QRectF(3.6, 3.6, 16.8, 16.8))
    return path


